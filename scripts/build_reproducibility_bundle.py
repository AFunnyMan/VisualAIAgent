def sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def blocked(path: Path) -> str | None:
    if set(path.parts) & BLOCKED_PARTS:
        return "environment, dependency cache, generated bytecode, or output bundle"
    if path.name.startswith(".env") and path.name != ".env.example":
        return "private environment configuration"
    if path.name in {".DS_Store", "Thumbs.db", "app.lock", ":memory:.ses"}:
        return "system metadata or runtime lock"
    if path.suffix in {".log", ".pyc", ".db", ".sqlite", ".sqlite3"} or any(
        suffix in path.name for suffix in (".sqlite3-", ".sqlite-", ".db-")
    ):
        return "full execution log, runtime database, or generated bytecode"
    return None


def _default_selected(path: Path) -> bool:
    parts = path.parts
    if len(parts) > 1 and parts[0] == "data":
        return parts[1].startswith(DATA_PREFIXES)
    if len(parts) > 2 and parts[:2] == ("harness", "artifacts"):
        name = parts[2]
        if name.startswith(ARTIFACT_PREFIXES):
            return True
        if name in {"ab-20260907", "recognition-v2-20260907"}:
            return len(parts) > 3 and parts[3] in {"holdout", "validation"}
        return len(parts) == 3 and (
            name.startswith(("public-", "wikimedia-")) or name == "ultralytics-bus.jpg"
        )
    return parts[0] == "models"


def _destination(source: str, catalog: dict, tracked: set[str]) -> str:
    path = Path(source)
    if source in tracked:
        return str(Path("source") / path)
    if path.suffix in {".pt", ".onnx", ".pth", ".safetensors"}:
        kind = "pretrained" if path.name in {"yolo26n.pt", "yolo26n-cls.pt"} else "reference"
        return str(Path("models") / kind / path)
    dataset_roots = sorted(
        catalog.get("datasets", []), key=lambda row: len(row["source_dir"]), reverse=True
    )
    for dataset in dataset_roots:
        base = Path(dataset["source_dir"])
        if path.is_relative_to(base):
            category = (
                "history/invalid-datasets"
                if dataset.get("validity") == "invalid"
                else "data/datasets"
            )
            return str(Path(category) / dataset["id"] / path.relative_to(base))
    if source.startswith("data/training-inbox/"):
        return str(Path("data/raw") / path)
    if any(word in path.name.lower() for word in ("annotation", "truth")):
        return str(Path("data/annotations") / path)
    if "rejected" in source or "before-category-review" in source or "历史" in source:
        return str(Path("history") / path)
    if "复核" in source or "对照" in source or "review" in source:
        return str(Path("history/reviews") / path)
    if path.suffix.lower() in {".png", ".jpg", ".jpeg", ".mkv", ".mp4", ".webm"}:
        return str(Path("data/raw") / path)
    return str(Path("provenance/originals") / path)


def _path_strings(value):
    if isinstance(value, str):
        yield value
    elif isinstance(value, dict):
        for child in value.values():
            yield from _path_strings(child)
    elif isinstance(value, list):
        for child in value:
            yield from _path_strings(child)


def select_files(root: Path, catalog: dict, source_files: list[str]) -> dict:
    root = root.resolve()
    tracked = set(source_files)
    included: set[str] = set()
    excluded: dict[str, dict] = {}
    for base in ("data", "harness/artifacts", "models"):
        for directory, dirs, files in os.walk(root / base, followlinks=False):
            parent = Path(directory).relative_to(root)
            kept_dirs = []
            for name in sorted(dirs):
                relative = parent / name
                reason = blocked(relative)
                if (root / relative).is_symlink():
                    reason = "symbolic link excluded; no external filesystem dependency"
                if reason:
                    excluded[str(relative)] = {"kind": "subtree", "reason": reason}
                else:
                    kept_dirs.append(name)
            dirs[:] = kept_dirs
            for name in sorted(files):
                relative = parent / name
                reason = blocked(relative)
                if (root / relative).is_symlink():
                    reason = "symbolic link excluded"
                if not reason and _default_selected(relative):
                    included.add(str(relative))
                else:
                    excluded[str(relative)] = {
                        "kind": "file",
                        "size": (root / relative).lstat().st_size,
                        "reason": reason
                        or "not part of YOLO training lineage or referenced evidence",
                    }
    for name in tracked:
        path = root / name
        if path.is_file() and not path.is_symlink() and not blocked(Path(name)):
            included.add(name)
    # Preserve original supervision/source files referenced from retained metadata.
    # Do not parse the complete COCO JSON; the selected subset already has a manifest.
    scanned: set[str] = set()
    while True:
        pending = [name for name in included - scanned if name.endswith(".json")]
        if not pending:
            break
        for name in pending:
            scanned.add(name)
            path = root / name
            if path.stat().st_size > 20 * 1024 * 1024:
                continue
            try:
                data = json.loads(path.read_text(encoding="utf-8"))
            except (ValueError, UnicodeError):
                continue
            for value in _path_strings(data):
                try:
                    original_candidate = Path(value)
                    candidate = root / original_candidate
                    if candidate.is_symlink():
                        continue
                    candidate = candidate.resolve()
                    if not candidate.is_relative_to(root) or not candidate.is_file():
                        continue
                except (OSError, ValueError):
                    continue
                relative = str(candidate.relative_to(root))
                if blocked(Path(relative)):
                    continue
                included.add(relative)
                excluded.pop(relative, None)
    destinations = {name: _destination(name, catalog, tracked) for name in sorted(included)}
    if len(set(destinations.values())) != len(destinations):
        raise ValueError("Destination collision in copy plan")
    return {"included": destinations, "excluded": excluded}


